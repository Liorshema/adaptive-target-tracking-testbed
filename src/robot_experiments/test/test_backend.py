def test_sessions_reference_runs_in_order_and_preserve_evidence_across_process_restart(tmp_path):
    import subprocess
    import sys
    first, path = recorded_run(tmp_path / 'results')
    second, other = recorded_run(tmp_path / 'results', outcome='readiness_timeout', noise=0.2)
    original = {p: hashlib.sha256(p.read_bytes()).hexdigest()
                for p in (tmp_path / 'results').rglob('*') if p.is_file()}
    api = backend(tmp_path, roots=[tmp_path / 'results'])
    session = api.create_session({'title': 'Compare', 'notes': 'A versus B'})
    api.add_run_to_session(session['session_id'], first)
    api.add_run_to_session(session['session_id'], first)
    api.add_run_to_session(session['session_id'], second)
    result = api.get_session_comparison(session['session_id'])
    assert [x['run_id'] for x in result['runs']] == [first, second]
    assert result['runs'][1]['metrics'].get('metrics') is None
    assert result['ranking'] is None
    assert result['comparability']['comparable'] is False
    assert result['comparability']['reasons']
    with pytest.raises(KeyError):
        api.add_run_to_session(session['session_id'], str(uuid.uuid4()))
    code = (
        'import json;from robot_experiments.backend import ExperimentBackend;'
        f'b=ExperimentBackend({str(api.directory)!r},'
        f'result_roots=[{str(tmp_path / "results")!r}]);'
        f'print(json.dumps(b.get_session_comparison({session["session_id"]!r})))')
    reopened = json.loads(subprocess.check_output([sys.executable, '-c', code]))
    assert [x['run_id'] for x in reopened['runs']] == [first, second]
    session_file = api.directory / 'sessions' / (session['session_id'] + '.json')
    stored = json.loads(session_file.read_text())
    assert stored['runs'] == [
        {'run_id': first, 'directory': str(path)}, {'run_id': second, 'directory': str(other)}]
    assert 'metrics' not in stored and 'telemetry' not in stored
    assert all(hashlib.sha256(p.read_bytes()).hexdigest() == digest
               for p, digest in original.items())


def test_concurrent_session_additions_are_atomic_and_deduplicated(tmp_path):
    import subprocess
    import sys
    first, _ = recorded_run(tmp_path / 'results')
    second, _ = recorded_run(tmp_path / 'results')
    api = backend(tmp_path, roots=[tmp_path / 'results'])
    session = api.create_session()
    api.add_run_to_session(session['session_id'], first)
    code = (
        'from robot_experiments.backend import ExperimentBackend;'
        f'b=ExperimentBackend({str(api.directory)!r},'
        f'result_roots=[{str(tmp_path / "results")!r}]);'
        f'b.add_run_to_session({session["session_id"]!r},{second!r})')
    children = [subprocess.Popen([sys.executable, '-c', code]) for _ in range(3)]
    for child in children:
        assert child.wait(timeout=15) == 0
    result = api.get_session_comparison(session['session_id'])
    assert [x['run_id'] for x in result['runs']] == [first, second]
    assert result['comparability']['comparable'] is True
    assert api.list_sessions()[0]['run_count'] == 2


