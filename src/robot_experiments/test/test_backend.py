def test_public_builder_save_conflict_and_reset_keep_original_revisions_and_defaults(tmp_path):
    catalog = ExperimentCatalog(tmp_path / 'catalog.yaml', share)
    catalog.initialize()
    api = backend(tmp_path, catalog=catalog)
    original = catalog.get('EXP-NOMINAL', 1)
    owners = {p: p.read_bytes() for p in SRC.rglob('*.yaml')}
    doc = api.new_draft('EXP-BACKEND', 'Backend experiment', 'EXP-NOMINAL', base_revision=1)
    doc['experiment']['parameters'] = {'target_dynamics': {'damping': 0.23}}
    assert api.validate_experiment(doc)['valid']
    record = api.save_experiment(doc)
    changed = deepcopy(doc)
    changed['experiment']['parameters']['target_dynamics']['damping'] = 0.31
    assert api.save_experiment(changed, expected_revision=1)['revision'] == 2
    with pytest.raises(CatalogConflict):
        api.save_experiment(doc, expected_revision=1)
    assert [x['revision'] for x in api.list_revisions('EXP-BACKEND')] == [1, 2]
    assert catalog.get('EXP-BACKEND', 1) == record
    assert catalog.get('EXP-NOMINAL', 1) == original
    reset = api.reset_draft(changed)
    assert 'parameters' not in reset['experiment']
    assert changed['experiment']['parameters']['target_dynamics']['damping'] == 0.31
    assert all(p.read_bytes() == data for p, data in owners.items())


def recorded_run(root, *, outcome='completed', seed=42, noise=0.01, run_id=None):
    """Minimal Runner-owned artifact schema; telemetry is read, never generated by backend."""
    from robot_experiments.comparison import comparison_views
    from robot_experiments.reporting import write_json
    run_id = run_id or str(uuid.uuid4())
    study = root / run_id
    run = study / 'runs' / 'variant_seed42'
    run.mkdir(parents=True)
    identity = {'id': 'EXP-RECORDED', 'revision': 1, 'definition_sha256': 'a' * 64}
    write_json(study / 'experiment_identity.json', identity)
    failed = outcome != 'completed'
    write_json(run / 'status.json', {
        'schema_version': 1, 'run_id': run_id, 'experiment_identity': identity,
        'execution_status': 'failed' if failed else 'completed',
        'acceptance': None if failed else True, 'started_utc': '2026-01-01T00:00:00+00:00',
        'error': {'code': outcome} if failed else None,
        'cleanup': {'returncode': 0, 'survivors': []}})
    write_json(run / 'metadata.json', {'schema_version': 1, 'run_id': run_id,
               'variant': 'variant', 'seed': seed, 'experiment_identity': identity})
    metric = {'available': True, 'unit': 'm', 'sample_count': 10, 'mean': 0.2, 'max': 0.3}
    write_json(run / 'metrics.json', {'schema_version': 1, 'available': False,
               'reason': {'code': outcome}} if failed else {
        'schema_version': 1, 'contract': {'time_basis': 'simulation source epoch'},
        'evaluation_window': {'start': 1.0, 'end': 3.0, 'unit': 's'},
        'metrics': {'tracking_distance': metric}, 'safety': {'coverage_complete': True}})
    view = comparison_views({'description': {'robot': 'fixture'}, 'duration': 2.0,
                             'measurements': {'noise': noise}}, None, {
        'evaluation': {'required_metrics': ['tracking_distance']},
        'seed_consumers': {'measurements.target_position.random_seed': seed}})
    write_json(run / 'comparison.json', view)
    write_json(run / 'resolved_configuration.json', {
        'experiment': {'name': 'recorded'}, 'context': {}, 'system': {'identities': {}},
        'owner_snapshot': {'seed_consumers': {'measurements.target_position.random_seed': seed},
                           'resources': {}, 'reproducibility': 'recorded RNG contract'}})
    (run / 'inputs').mkdir()
    (run / 'inputs' / 'system.yaml').write_text('schema_version: 2\n')
    (run / 'telemetry').mkdir()
    (run / 'telemetry' / 'clock.jsonl').write_text(
        ''.join(json.dumps({'time': x}) + '\n' for x in range(10)))
    return run_id, run


def test_recorded_results_keep_execution_safety_and_unavailable_attempts_separate(tmp_path):
    complete, path = recorded_run(tmp_path / 'results')
    timeout, failed = recorded_run(tmp_path / 'results', outcome='readiness_timeout')
    before = {p: p.read_bytes() for p in tmp_path.rglob('*') if p.is_file()}
    api = backend(tmp_path, roots=[tmp_path / 'results'])
    rows = api.list_runs(limit=1)
    assert len(rows) == 1
    assert api.get_run_status(complete)['execution_status'] == 'completed'
    good = api.get_run_results(complete)
    assert good['status']['acceptance'] is True
    assert good['metrics']['metrics']['tracking_distance']['mean'] == 0.2
    unknown = api.get_run_results(timeout)
    assert unknown['status']['acceptance'] is None
    assert unknown['metrics']['available'] is False
    assert unknown['metrics'].get('metrics') is None
    assert unknown['status']['error']['code'] == 'readiness_timeout'
    assert unknown['artifacts']['time_series'] is None
    assert good['artifacts']['frozen_inputs'] == str(path / 'inputs')
    assert api.read_telemetry(complete, 'clock', offset=3, limit=2)['records'] == [
        {'time': 3}, {'time': 4}]
    with pytest.raises(ValueError):
        api.read_telemetry(complete, '../status')
    assert len(api.list_runs(filters={'execution_status': 'failed'})) == 1
    assert all(p.read_bytes() == data for p, data in before.items())
    with pytest.raises(KeyError):
        api.get_run_results(str(uuid.uuid4()))


