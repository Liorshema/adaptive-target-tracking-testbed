def test_job_identity_actuation_opt_in_and_cooperative_stop(tmp_path, monkeypatch):
    import os
    import threading
    import time
    from types import SimpleNamespace
    from robot_experiments import jobs
    from robot_experiments.reporting import write_json
    api = backend(tmp_path)
    # The external worker process is exercised with ROS/Gazebo in installed checks.
    # Here keep actual validation, request/status files and cooperative stop logic.
    monkeypatch.setattr(jobs.subprocess, 'Popen',
                        lambda *args, **kwargs: SimpleNamespace(pid=os.getpid()))
    initial = api.start_run('EXP-NOMINAL', 3, output=tmp_path / 'results')
    assert initial['run_ids'] == [] and initial['state'] == 'queued'
    job_id = initial['job_id']
    job_dir = api.jobs.directory / job_id
    request = json.loads((job_dir / 'request.json').read_text())
    assert request['runtime_overrides'] == {'enable_actuation': False, 'gui': False}
    assert request['record']['revision'] == 3
    run_id, run = recorded_run(tmp_path / 'results')
    write_json(job_dir / 'status.json',
               {'job_id': job_id, 'state': 'running', 'study': str(run.parent.parent)})
    live = api.get_job_status(job_id)
    assert live['run_ids'] == [run_id] and live['run_ids'][0] != job_id

    def complete():
        deadline = time.monotonic() + 10
        while not (job_dir / 'stop.request').exists() and time.monotonic() < deadline:
            time.sleep(0.01)
        write_json(job_dir / 'status.json', {'job_id': job_id, 'state': 'cancelled',
                                             'study': str(run.parent.parent)})

    worker = threading.Thread(target=complete)
    worker.start()
    assert api.cancel_run(run_id)['state'] == 'cancelled'
    worker.join(10)
    assert api.cancel_run(run_id)['state'] == 'cancelled'
    assert (job_dir / 'stop.request').exists()
    assert api.get_run_status(run_id)['cleanup']['survivors'] == []
    assert api.gazebo_setup_capabilities()['interactive_setup_supported'] is True


